def seed_user(database: Database, user_id: str) -> None:
    """Insert a User row with a fixed id — workspace_access/workspace_remotes/jobs FK to
    users.id, and several tests need a predictable id (e.g. "u1") rather than one
    generated by UserRepository.create. A no-op if the id already exists, so a file's own
    explicit seeding and an autouse fixture calling this for the same id don't collide."""
    with Session(database.engine) as session:
        if session.get(User, user_id) is not None:
            return
        session.add(
            User(
                id=user_id,
                email=f"{user_id}@test.com",
                password_hash="x",
                created_at="2026-01-01",
            )
        )
        session.commit()


