import os
import sysconfig
import tempfile
from collections.abc import Callable, Iterator
from pathlib import Path

import pytest

# Some test modules import sqlalchemy before kajet_turbo, bypassing the guard
# in kajet_turbo/__init__.py — set it here too (conftest runs first), so the
# GIL stays disabled on free-threaded builds.
if sysconfig.get_config_var("Py_GIL_DISABLED"):
    os.environ.setdefault("DISABLE_SQLALCHEMY_CEXT_RUNTIME", "1")

# kajet_turbo.dependencies runs Database() and create_auth() at module level on import.
# Both need env vars set before test files are collected by pytest.
if "DB_PATH" not in os.environ:
    _db_fd, _db_path = tempfile.mkstemp(suffix=".db")
    os.close(_db_fd)  # SQLite reopens the (empty) file itself
    os.environ["DB_PATH"] = _db_path
if "MCP_BASE_URL" not in os.environ:
    os.environ["MCP_BASE_URL"] = "http://localhost:8000"


def pytest_configure(config):
    # pytest-xdist workers inherit DB_PATH from the controller process and would
    # all run alembic upgrade head on the same file simultaneously → race.
    # Override to a per-worker temp file before any test file is collected.
    worker_input = getattr(config, "workerinput", None)
    if worker_input is not None:
        worker_id = worker_input.get("workerid", "gw0")
        fd, path = tempfile.mkstemp(suffix=f"-{worker_id}.db")
        os.close(fd)
        os.environ["DB_PATH"] = path
        return

    # pytest's default basetemp (pytest-of-<user>/pytest-<N>, last-3 retention) is one
    # shared pool per OS user: independent pytest invocations from different worktrees
    # (or two runs of this suite started close together) race for numbered dirs and can
    # have a still-running run's tmp_path directory garbage-collected out from under it
    # (pytest-dev/pytest#7911, pytest-dev/py#30). mkdtemp sidesteps the shared pool
    # entirely — every invocation gets its own OS-guaranteed-unique directory, so two
    # worktrees (or two overlapping runs anywhere) never share one. Only the controller
    # sets this; xdist already nests worker basetemps under whatever the controller
    # picks, same as it does with the default. Skip if the caller passed --basetemp
    # explicitly — that is an intentional override we should not fight.
    if config.option.basetemp is None:
        config.option.basetemp = tempfile.mkdtemp(prefix="kajet-pytest-")


